/*
Usage Suggestions:
 
Backgrounds: Use the primary background color.
 
Text: Primary text with the designated text color, secondary text with the secondary text color.
 
Interactive Elements (Buttons, Icons, Links): Accent color for active states, secondary text color for inactive/subtle states.
 
Map Elements: The accent color is great for markers, while subtle highlight colors could be used for specific regions or paths.
 
Cards/Containers: A slightly different shade of the background color or the subtle highlight color can differentiate containers without breaking the minimalistic feel.
 
Pop-ups/Modals: Could use a slightly lighter version of the background color in dark mode, or a slightly darker/more opaque version of the background in light mode to create a sense of elevation.

*/
